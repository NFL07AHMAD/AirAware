// Peta Asia Tenggara sederhana berbasis koordinat asli [bujur, lintang].
// Kota dan daratan memakai proyeksi yang sama, jadi posisinya selalu konsisten.

export const MAP_SIZE = 600;
const CENTER_LON = 110;
const CENTER_LAT = 7;
const PX_PER_DEG = 15; // 600px = 40 derajat

export function toMapPoint(lon, lat) {
  return {
    x: MAP_SIZE / 2 + (lon - CENTER_LON) * PX_PER_DEG,
    y: MAP_SIZE / 2 - (lat - CENTER_LAT) * PX_PER_DEG,
  };
}

// Haluskan sudut poligon (Chaikin) supaya garis pantai tidak kaku.
function chaikin(points, iterations = 2) {
  let pts = points;
  for (let n = 0; n < iterations; n++) {
    const next = [];
    for (let i = 0; i < pts.length; i++) {
      const a = pts[i];
      const b = pts[(i + 1) % pts.length];
      next.push([a[0] * 0.75 + b[0] * 0.25, a[1] * 0.75 + b[1] * 0.25]);
      next.push([a[0] * 0.25 + b[0] * 0.75, a[1] * 0.25 + b[1] * 0.75]);
    }
    pts = next;
  }
  return pts;
}

function toPath(points, smooth = true) {
  const pts = smooth ? chaikin(points) : points;
  return (
    pts
      .map(([lon, lat], i) => {
        const { x, y } = toMapPoint(lon, lat);
        return `${i === 0 ? "M" : "L"}${x.toFixed(1)} ${y.toFixed(1)}`;
      })
      .join(" ") + "Z"
  );
}

