// Garis lintang/bujur (graticule) setiap 10°
export const graticule = (() => {
  const lines = [];
  for (let lon = 90; lon <= 130; lon += 10) {
    const a = toMapPoint(lon, 27);
    const b = toMapPoint(lon, -13);
    lines.push({ key: `lon-${lon}`, d: `M${a.x} ${a.y} L${b.x} ${b.y}`, major: false });
  }
  for (let lat = -10; lat <= 20; lat += 10) {
    const a = toMapPoint(90, lat);
    const b = toMapPoint(130, lat);
    lines.push({ key: `lat-${lat}`, d: `M${a.x} ${a.y} L${b.x} ${b.y}`, major: lat === 0 });
  }
  return lines;
})();